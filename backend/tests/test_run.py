"""Tests for the live scenario run (POST /scenes/{id}/run).

The run loop is what makes the sliders mean something, so the tests pin the
three things a planner would be misled by if they drifted:

1. **A baseline run reproduces the committed overlay.** The offline artefact
   was generated by scripts/make_wetgrid.py at 450 mm; a live run at 450 mm
   must produce the same volume and wet area, or the "run" button and the
   artefact the user can see are two different models.
2. **Rainfall moves the answer monotonically.** More rain -> more unstored
   water and a larger wet area. A level-pool solver that could go backwards
   would be a bug the map would make look like a feature.
3. **The heatwave preset is a display transform, not a scenario.** The blended
   field must change, the land-class heat index must not: the physics does not
   know about air temperature, and a run that quietly changed it would be
   claiming a temperature model this project does not have.

Plus the honesty checks: every response carries the screening status and
warning, the explanation says which source produced it, and an out-of-range
rainfall is refused rather than extrapolated.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
for _extra in (BACKEND_DIR, BACKEND_DIR / "scripts"):
    if str(_extra) not in sys.path:
        sys.path.insert(0, str(_extra))

# A run writes overlay PNGs and sidecars under data/rasters/run/, so this suite
# writes into a throwaway copy of the store rather than the real one. Must
# precede the app imports so paths resolve late.
sys.path.insert(0, str(BACKEND_DIR / "tests"))
from _tmpstore import isolate_store  # noqa: E402

isolate_store()

from app.config import settings  # noqa: E402
from app.services import run_service  # noqa: E402
from app.services.sandbox_model import load_grids  # noqa: E402

PASSED = 0
FAILED = 0

def _seeded_scene_id() -> str:
    """The committed scene fixture's id, without hard-coding its UUID.

    The store's filename is the id (``data/scenes/<uuid>.json``), which is how
    ``db.scene_path`` resolves one, so the file name is the id and reading the
    document is unnecessary.
    """
    docs = sorted((BACKEND_DIR / "data" / "scenes").glob("*.json"))
    if not docs:
        raise SystemExit("no seeded scene in data/scenes; run scripts/seed_scene.py")
    return docs[0].stem


SCENE_ID = _seeded_scene_id()
SIDECAR = json.loads(
    (BACKEND_DIR / "data" / "rasters" / "wetgrid_hsk.json").read_text(
        encoding="utf-8"))
# The committed artefact's own rainfall: the baseline run must be scored at the
# same depth to reproduce it (the artefact moved 450 -> 50 mm when the slider
# default became intensity x duration).
ARTEFACT_MM = float(SIDECAR["inputs"]["rainfall_mm"])


def check(label: str, ok: bool, detail: str = "") -> None:
    global PASSED, FAILED
    if ok:
        PASSED += 1
        print(f"  PASS  {label}{f' -- {detail}' if detail else ''}")
    else:
        FAILED += 1
        print(f"  FAIL  {label}{f' -- {detail}' if detail else ''}")


def main() -> int:
    grids = load_grids()
    check("the rasters load", grids is not None)
    if grids is None:
        print("\n0/1 checks passed")
        return 1

    # ---- 1. a baseline run is the committed overlay ------------------------
    base = run_service.run_scenario(SCENE_ID, ARTEFACT_MM, 30.0, None, [])
    check("a run returns the screening status",
          base["status"] == run_service.RUN_STATUS, base["status"])
    check("and the screening warning is in the body",
          "flood extent" in base["warning"].lower()
          or "not engineering-grade" in base["warning"].lower())

    # The provenance receipt on a chat card reads these, so they must be the real
    # sources the run used, never a placeholder the UI would then repeat.
    check("a run names the data it stood on",
          base["sources"]["terrain"] == "open3dhk-tiles"
          and base["sources"]["landCover"] == "esa-worldcover",
          str(base.get("sources")))
    check("and the heat anchor, which is optional, is named or explicitly None",
          "lst" in base["sources"])

    offline = SIDECAR["results"]
    check("the baseline unstored volume is the offline artefact's",
          abs(base["stats"]["baseline"]["unstoredM3"]
              - offline["unstoredVolumeM3"]) < 1.0,
          f"{base['stats']['baseline']['unstoredM3']:,.1f} vs "
          f"{offline['unstoredVolumeM3']:,.1f} m3")
    check("the baseline wet area is the offline artefact's",
          abs(base["stats"]["baseline"]["wetAreaHa"]
              - offline["wetAreaHa"]) < 0.05,
          f"{base['stats']['baseline']['wetAreaHa']:.2f} vs "
          f"{offline['wetAreaHa']:.2f} ha")
    check("a baseline run moves nothing against itself",
          abs(base["stats"]["delta"]["unstoredM3"]) < 1.0
          and abs(base["stats"]["delta"]["wetAreaHa"]) < 0.05, "")
    check("and it reports no interventions as applied or skipped",
          not base["interventionsApplied"] and not base["interventionsSkipped"])
    # The run publishes the shares a card may quote, so a derived
    # percentage grounds instead of being flagged as ungrounded.
    ratios = base["stats"]["ratios"]
    check("the run publishes its derived shares",
          abs(ratios["unstoredOverRunoff"]
              - base["stats"]["scenario"]["unstoredM3"]
              / base["stats"]["scenario"]["runoffM3"]) < 1e-5,
          f"unstoredOverRunoff={ratios['unstoredOverRunoff']:.4f}")

    # ---- 2. rainfall moves the answer, one way -----------------------------
    wet = run_service.run_scenario(SCENE_ID, 300.0, 30.0, None, [])
    storm = run_service.run_scenario(SCENE_ID, 600.0, 30.0, None, [])
    check("more rainfall leaves more unstored water",
          storm["stats"]["scenario"]["unstoredM3"]
          > wet["stats"]["scenario"]["unstoredM3"],
          f"{wet['stats']['scenario']['unstoredM3']:,.0f} -> "
          f"{storm['stats']['scenario']['unstoredM3']:,.0f} m3")
    check("and ponds over more ground",
          storm["stats"]["scenario"]["wetAreaHa"]
          > wet["stats"]["scenario"]["wetAreaHa"],
          f"{wet['stats']['scenario']['wetAreaHa']:.1f} -> "
          f"{storm['stats']['scenario']['wetAreaHa']:.1f} ha")
    check("three runs produce three different overlay timestamps",
          len({base["runId"], wet["runId"], storm["runId"]}) == 3)

    # ---- 3. temperature re-anchors the surface field, not the water ---------
    hot = run_service.run_scenario(SCENE_ID, ARTEFACT_MM, 38.0, None, [])
    check("the scenario mean surface temperature follows the slider",
          abs(hot["stats"]["scenario"]["surfaceMeanC"] - 38.0) < 0.01,
          f"{hot['stats']['scenario']['surfaceMeanC']:.2f} C")
    check("a higher scenario mean shifts the field up",
          hot["stats"]["scenario"]["surfaceMeanC"]
          > base["stats"]["scenario"]["surfaceMeanC"],
          f"{base['stats']['scenario']['surfaceMeanC']:.2f} -> "
          f"{hot['stats']['scenario']['surfaceMeanC']:.2f} C")
    check("and does NOT move the water: the wet area is identical",
          abs(hot["stats"]["scenario"]["wetAreaHa"]
              - base["stats"]["scenario"]["wetAreaHa"]) < 1e-9)
    check("or the unstored volume",
          abs(hot["stats"]["scenario"]["unstoredM3"]
              - base["stats"]["scenario"]["unstoredM3"]) < 1e-9)

    # ---- 4. an intervention moves the ledger -------------------------------
    # A retention basin in the middle of the study area, small enough to pass
    # the coverage guard, built here rather than read from the store so the
    # test does not depend on which plans happen to be seeded.
    x0, y0, x1, y1 = grids.bounds
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    # Sized to the real study area (a small fraction of the extent), not a fixed
    # degree count: 0.004° used to be "well under 25%", but the real bounds are
    # far smaller and 0.004° is now the whole grid. ~1/8 of each axis -> ~1.5% coverage.
    span = (x1 - x0) / 8.0
    span = min(span, (y1 - y0) / 8.0)
    ring = [[cx - span, cy - span], [cx + span, cy - span],
            [cx + span, cy + span], [cx - span, cy + span],
            [cx - span, cy - span]]
    features = [{"id": "test-basin", "intervention_type": "flood_storage",
                 "geometry": {"type": "Polygon", "coordinates": [ring]},
                 "params": {"basis": "test"}}]
    run_with = run_service.run_scenario(SCENE_ID, ARTEFACT_MM, 30.0, "test-plan",
                                        features)
    check("a retention basin is applied to the grid",
          len(run_with["interventionsApplied"]) == 1,
          (str(run_with["interventionsApplied"][0]["areaM2"])
           if run_with["interventionsApplied"] else "none applied"))
    check("and it leaves less water unstored than today",
          run_with["stats"]["delta"]["unstoredM3"] < -1.0,
          f"{run_with['stats']['delta']['unstoredM3']:,.0f} m3")
    check("so the run is reported as not worsening the site",
          run_with["worsens"] is False)
    check("the scenario's wet area shrinks with it",
          run_with["stats"]["delta"]["wetAreaHa"] < 0,
          f"{run_with['stats']['delta']['wetAreaHa']:.2f} ha")

    # ---- 5. an intervention with no land-cover effect is reported, not faked
    noop = [{"id": "test-drain", "intervention_type": "drainage_alignment",
             "geometry": {"type": "Polygon", "coordinates": [ring]},
             "params": {}}]
    run_noop = run_service.run_scenario(SCENE_ID, ARTEFACT_MM, 30.0, "test-plan",
                                        noop)
    check("an intervention the model cannot score is skipped with a reason",
          len(run_noop["interventionsSkipped"]) == 1
          and bool(run_noop["interventionsSkipped"][0]["why"]),
          run_noop["interventionsSkipped"][0]["why"][:60])
    check("and it changes no water",
          abs(run_noop["stats"]["delta"]["unstoredM3"]) < 1.0)

    # ---- 6. the overlays are real files, cache-busted, per-run -------------
    #
    # Per-run names (not a fixed `wetgrid.png`) because a fixed name let two
    # planners running at once overwrite each other's overlay. The run id is in
    # the filename AND the query string, so this pins both.
    for key, prefix in (("wetGridUrl", "wetgrid"), ("heatmapUrl", "heatmap")):
        url = base["overlays"][key]
        name = f"{prefix}_{base['runId']}.png"
        check(f"{key} points at the live render",
              name in url and f"?v={base['runId']}" in url, url)
        path = settings.rasters_dir / "run" / name
        check(f"{name} is a PNG on disk",
              path.exists() and path.read_bytes()[:4] == b"\x89PNG",
              f"{path.stat().st_size:,} bytes")
    sidecar = (settings.rasters_dir / "run" / f"wetgrid_{base['runId']}.json")
    check("the wet-grid sidecar records the run's inputs",
          json.loads(sidecar.read_text())["inputs"]["rainfallMm"] == ARTEFACT_MM)

    # ---- 7. honesty and refusal --------------------------------------------
    check("the explanation names the rainfall the run used",
          f"{ARTEFACT_MM:g} mm" in base["explanation"], base["explanation"][:70] + "…")
    check("and says it is a screening flood extent",
          "flood" in base["explanation"].lower())
    check("the explanation source is reported, never implied",
          base["explanationSource"] in ("anthropic", "openai-compatible",
                                        "template"),
          base["explanationSource"])

    try:
        run_service.run_scenario(SCENE_ID, 5000.0, 30.0, None, [])
        check("out-of-range rainfall is refused", False, "no error raised")
    except run_service.RunInputsError as exc:
        check("out-of-range rainfall is refused", "must be 0-" in str(exc),
              str(exc))

    print(f"\n{PASSED}/{PASSED + FAILED} passed")
    return 1 if FAILED else 0


if __name__ == "__main__":
    raise SystemExit(main())
