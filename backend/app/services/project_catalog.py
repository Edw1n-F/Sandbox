"""The fixed project catalog, served to the frontend (P0.1 of the loop plan).

``ProjectCatalog.tsx`` used to construct its four projects in TypeScript and
send a *sentence* per phase to the AI planner, which re-derived a footprint on
every toggle. The panel flagged that in its own caption. This module is the
other half of the fix: the catalog now lives in one place
(``backend/data/projects.json``, generated by
``scripts/make_project_catalog.py`` from the real rasters) and the frontend
reads it instead of imagining it.

Two properties matter, and both are enforced here rather than trusted:

- **Determinism.** The same phase twice is the same geometry, so composing
  phases is reproducible and a before/after comparison means something.
- **Provenance travels with the geometry.** Every project carries ``source``,
  ``date`` and ``confidence``; every intervention carries ``provenance``. The
  frontend renders them, so a user can see that a footprint is a candidate
  parcel read from land cover at 5 m and not a surveyed site.

The document is validated on load and a malformed catalog is a 500, not a
silently truncated list: an UI that quietly shows three of four projects
because the fourth had a typo in it is worse than an error.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

from app.config import settings

SCHEMA = "hack4sdg/project-catalog@1"

_GEOMETRY_TYPES = {"Point", "LineString", "Polygon"}


class CatalogError(RuntimeError):
    """The catalog on disk is not the catalog the schema promises."""


def _validate(doc: Any) -> dict[str, Any]:
    """Check the shape of the loaded document, and return it unchanged.

    Checks the things that would otherwise be discovered by a user as a blank
    panel: the schema marker, at least one project, unique ids, phases that
    carry at least one intervention, and geometry that is a real GeoJSON
    geometry inside EPSG:4326.
    """
    if not isinstance(doc, dict):
        raise CatalogError("catalog is not a JSON object")
    if doc.get("schema") != SCHEMA:
        raise CatalogError(
            f"catalog schema is {doc.get('schema')!r}, expected {SCHEMA!r}")
    if not doc.get("warning"):
        raise CatalogError("catalog has no warning text; honesty is load-bearing")
    projects = doc.get("projects")
    if not isinstance(projects, list) or not projects:
        raise CatalogError("catalog has no projects")

    seen_projects: set[str] = set()
    for project in projects:
        for key in ("id", "name", "note", "axis", "source", "date",
                    "confidence", "phases"):
            if not project.get(key):
                raise CatalogError(f"project {project.get('id')!r} lacks {key}")
        if project["id"] in seen_projects:
            raise CatalogError(f"duplicate project id {project['id']!r}")
        seen_projects.add(project["id"])

        seen_phases: set[str] = set()
        for phase in project["phases"]:
            for key in ("id", "label", "interventions", "grounding"):
                if not phase.get(key):
                    raise CatalogError(
                        f"{project['id']}/{phase.get('id')!r} lacks {key}")
            if phase["id"] in seen_phases:
                raise CatalogError(
                    f"duplicate phase id {project['id']}/{phase['id']}")
            seen_phases.add(phase["id"])
            if not isinstance(phase["interventions"], list) or not phase["interventions"]:
                raise CatalogError(
                    f"{project['id']}/{phase['id']} has no interventions")

            for feature in phase["interventions"]:
                geometry = (feature.get("geometry") or {})
                if geometry.get("type") not in _GEOMETRY_TYPES:
                    raise CatalogError(
                        f"{project['id']}/{phase['id']} has geometry type "
                        f"{geometry.get('type')!r}")
                if not feature.get("intervention_type"):
                    raise CatalogError(
                        f"{project['id']}/{phase['id']} has an intervention "
                        "without a type")
                if not (feature.get("provenance") or {}).get("why"):
                    raise CatalogError(
                        f"{project['id']}/{phase['id']} has an intervention "
                        "without provenance")
                coordinates = geometry.get("coordinates")
                for position in _flatten(coordinates or []):
                    lon, lat = position
                    if not (-180.0 <= lon <= 180.0) or not (-90.0 <= lat <= 90.0):
                        raise CatalogError(
                            f"{project['id']}/{phase['id']} has a coordinate "
                            f"outside EPSG:4326: [{lon}, {lat}]")
    return doc


def _flatten(coords: Any) -> list[tuple[float, float]]:
    """Every (lon, lat) position in an arbitrarily nested coordinate list."""
    if (isinstance(coords, (list, tuple)) and len(coords) >= 2
            and all(isinstance(c, (int, float)) for c in coords[:2])):
        return [(float(coords[0]), float(coords[1]))]
    out: list[tuple[float, float]] = []
    if isinstance(coords, (list, tuple)):
        for item in coords:
            out.extend(_flatten(item))
    return out


@lru_cache(maxsize=8)
def _load(path: Path | None = None) -> dict[str, Any]:
    """Read, validate and cache the catalog document.

    Keyed on the path, so a test that points at a fixture gets that file and
    not the committed one, and the live process reads the real catalog once.
    """
    if path is None:
        path = settings.data_dir / "projects.json"
    if not path.exists():
        raise CatalogError(
            f"no catalog at {path}; run scripts/make_project_catalog.py")
    return _validate(json.loads(path.read_text(encoding="utf-8")))


def load_catalog(path: Path | None = None) -> dict[str, Any]:
    """The catalog document, validated. Raises ``CatalogError`` if it is bad."""
    return _load(path)


def phase_plan_payload(project_id: str, phase_id: str) -> dict[str, Any]:
    """A ``PlanCreate`` body for one catalog phase.

    The geometry is copied verbatim from the catalog: no re-derivation, no
    re-siting, no natural language. ``source`` is ``manual`` because a human
    curated this catalog -- calling it ``ai`` would credit a model for a
    footprint a person signed off, and the two behave differently in the UI.
    """
    catalog = load_catalog()
    for project in catalog["projects"]:
        if project["id"] != project_id:
            continue
        for phase in project["phases"]:
            if phase["id"] != phase_id:
                continue
            return {
                "plan_type": "custom",
                "label": f"{project['name']} - {phase['label']}",
                "source": "manual",
                "params": {
                    "projectId": project_id,
                    "phaseId": phase_id,
                    "catalogDate": project["date"],
                    "catalogConfidence": project["confidence"],
                },
                "interventions": [
                    {
                        "geometry": f["geometry"],
                        "intervention_type": f["intervention_type"],
                        "source": "manual",
                        "params": {**(f.get("params") or {}),
                                   "provenance": f.get("provenance") or {}},
                        "style": f.get("style") or {},
                    }
                    for f in phase["interventions"]
                ],
            }
    raise KeyError(f"no phase {project_id}/{phase_id} in the catalog")
